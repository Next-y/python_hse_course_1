def validate(pushed, popped):

    stack = []
    pop_index = 0

    for value in pushed:
        stack.append(value)

        while (
            stack
            and pop_index < len(popped)
            and stack[-1] == popped[pop_index]
        ):
            stack.pop()
            pop_index += 1

    return pop_index == len(popped)


# Объяснение решения
# По условию элементы уникальны, popped — перестановка pushed.
# Имитируем работу стека с помощью списка:
# append добавляет на вершину, pop удаляет с вершины, stack[-1] читает вершину.
# pop_index — количество уже выполненных извлечений и индекс следующего
# элемента, который требуется извлечь согласно popped.
#
# Перебираем pushed и добавляем очередное число в стек. Затем, пока вершина
# совпадает с popped[pop_index], извлекаем её и увеличиваем pop_index.
# Используем while, потому что одно добавление может разрешить сразу несколько
# извлечений. Если вершина не подходит, пробуем добавить следующее число.
# В конце возвращаем True, только если выполнили все требуемые извлечения.
#
# Почему все работает правильно
# После каждого извлечения полученный порядок равен началу popped длины
# pop_index. Если вершина совпала с требуемым числом, его можно извлечь сразу:
# добавление сверху другого уникального числа лишь закроет доступ к нему,
# а извлечь это другое число раньше нельзя по заданному порядку popped.
# Если вершина не совпадает, извлекать её нельзя; единственный возможный
# следующий шаг — добавление очередного числа из pushed.
# Так мы выполняем допустимые операции, не упуская возможного решения.
# Если pushed закончилась, а popped выполнена не полностью, нужный элемент
# заблокирован другим элементом и продолжить извлечения в заданном порядке нельзя.


# Оценка сложности
# Пусть n = len(pushed) = len(popped).
# Временная сложность: O(n). Каждый элемент добавляется один раз и удаляется не более одного
# раза. Хотя while находится внутри for, всего успешных итераций while не больше n.
# Добавление в конец списка Python занимает O(1) амортизированно: отдельное
# расширение может стоить O(n), но суммарная стоимость n добавлений — O(n).
# Память: O(n) дополнительно, потому что стек может хранить все n элементов.
# Например, это происходит перед первым извлечением при обратном порядке popped.
# Остальные переменные занимают O(1) памяти. 


# Визуализация работы алгоритма
# В таблицах вершина стека справа. j — значение pop_index после операции.
# «Нужно» — popped[j]; прочерк означает, что все извлечения уже выполнены.
# Отдельно показано каждое добавление и каждое извлечение внутри while.
#
# Пример 1: допустимый порядок с несколькими извлечениями подряд
# pushed = [2, 4, 6, 8, 10, 12]
# popped = [4, 8, 6, 12, 10, 2]
#
# Шаг | Операция | Стек после операции | j | Нужно
# ----|----------|---------------------|---|------
#  0  | начало   | []                  | 0 | 4
#  1  | push(2)  | [2]                 | 0 | 4
#  2  | push(4)  | [2, 4]              | 0 | 4
#  3  | pop()=4  | [2]                 | 1 | 8
#  4  | push(6)  | [2, 6]              | 1 | 8
#  5  | push(8)  | [2, 6, 8]           | 1 | 8
#  6  | pop()=8  | [2, 6]              | 2 | 6
#  7  | pop()=6  | [2]                 | 3 | 12
#  8  | push(10) | [2, 10]             | 3 | 12
#  9  | push(12) | [2, 10, 12]         | 3 | 12
# 10  | pop()=12 | [2, 10]             | 4 | 10
# 11  | pop()=10 | [2]                 | 5 | 2
# 12  | pop()=2  | []                  | 6 | —
#
# После шага 1 while не выполняется: 2 != 4. После шага 3 он останавливается,
# потому что теперь нужно 8, а сверху 2. На шаге 4 сверху 6, поэтому ждём 8.
# После push(8) while выполняется дважды: удаляет 8, затем открывшуюся 6.
# Останавливается на 2, так как следующее требуемое число — 12.
# После push(10) совпадения нет. После push(12) один запуск while извлекает
# сразу 12, 10 и 2. pop_index = 6 = len(popped), результат True.
#
# Пример 2: невозможный порядок, ошибка обнаруживается после успешных извлечений
# pushed = [2, 4, 6, 8, 10, 12]
# popped = [4, 8, 2, 12, 10, 6]
#
# Шаг | Операция | Стек после операции | j | Нужно
# ----|----------|---------------------|---|------
#  0  | начало   | []                  | 0 | 4
#  1  | push(2)  | [2]                 | 0 | 4
#  2  | push(4)  | [2, 4]              | 0 | 4
#  3  | pop()=4  | [2]                 | 1 | 8
#  4  | push(6)  | [2, 6]              | 1 | 8
#  5  | push(8)  | [2, 6, 8]           | 1 | 8
#  6  | pop()=8  | [2, 6]              | 2 | 2
#  7  | push(10) | [2, 6, 10]          | 2 | 2
#  8  | push(12) | [2, 6, 10, 12]      | 2 | 2
#
# Первые два извлечения, 4 и 8, успешны. После шага 6 требуется извлечь 2,
# но над ним лежит 6. Удалять 6 сейчас нельзя: следующим в popped записано 2.
# Реализация продолжает for: добавляет 10, затем 12. После каждого добавления
# проверка while не проходит, так как вершины 10 и 12 не равны 2.
# Вход закончился, pop_index = 2 != 6. Возвращаем False.
# До числа 2 можно добраться только извлекая другие числа раньше него,
# а это нарушит заданный порядок.
