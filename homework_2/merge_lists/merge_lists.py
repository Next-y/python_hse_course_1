class Node:
    #Узел односвязного списка: значение и ссылка на следующий узел

    def __init__(self, value, next_node=None):
        self.value = value
        self.next = next_node


def merge_with_dummy(list1, list2):
    #Объединить исходные узлы, используя один фиктивный начальный узел
    dummy = Node(0)
    tail = dummy

    while list1 is not None and list2 is not None:
        if list1.value <= list2.value:
            tail.next = list1
            list1 = list1.next
        else:
            tail.next = list2
            list2 = list2.next

        tail = tail.next

    tail.next = list1 if list1 is not None else list2
    return dummy.next


def merge_without_dummy(list1, list2):
    #Объединить исходные узлы без создания дополнительных узлов.
    if list1 is None:
        return list2
    if list2 is None:
        return list1

    if list1.value <= list2.value:
        head = list1
        list1 = list1.next
    else:
        head = list2
        list2 = list2.next

    tail = head

    while list1 is not None and list2 is not None:
        if list1.value <= list2.value:
            tail.next = list1
            list1 = list1.next
        else:
            tail.next = list2
            list2 = list2.next

        tail = tail.next

    tail.next = list1 if list1 is not None else list2
    return head


# Объяснение решения
# list1 и list2 — головы отсортированных по неубыванию односвязных списков.
# Пустой список - None. Предполагается, что списки не содержат
# циклов и не имеют общих узлов. Повторяющиеся значения допустимы.
# Результат — голова списка из исходных узлов в порядке неубывания; значения не копируем в новые узлы.
# Функции меняют ссылки next исходных списков. Поэтому для повторного слияния
# или проверки другого способа нужно заново построить входные списки.
#
# В обоих способах list1 и list2 указывают на первые ещё не выбранные узлы.
# Сравниваем их значения, присоединяем меньший узел через tail.next,
# передвигаем указатель соответствующего входного списка и затем tail.
# При равенстве выбираем узел из list1. Когда один список закончился,
# присоединяем весь остаток другого одной операцией: он уже отсортирован.
#
# 1. С фиктивным элементом: создаём dummy и начинаем с tail = dummy.
# Первый узел можно добавить обычной операцией tail.next = ... .
# Настоящая голова результата — dummy.next. Сам dummy в результат не входит.
# Значение 0 у dummy произвольное: оно не участвует в сравнениях.
#
# 2. Без фиктивного элемента: сначала отдельно обрабатываем пустые списки.
# Затем выбираем меньшую из двух голов как head и передвигаем соответствующий
# входной указатель. Устанавливаем tail = head и продолжаем тот же цикл слияния.
# head сохраняет начало результата, а tail движется по выбранным узлам.
#
# Почему оба способа корректны
# Минимальный среди оставшихся элементов находится в одной из двух голов:
# внутри каждого списка элементы уже отсортированы. Поэтому очередной выбранный
# узел не меньше предыдущего, и выбранный префикс остаётся отсортированным.
# Каждый шаг передвигает ровно один входной указатель, поэтому каждый исходный
# узел выбирается один раз. После цикла остаток второго списка не меньше tail
# и уже отсортирован; его присоединение сохраняет порядок и все исходные узлы.
# Различается только выбор первого узла, основной принцип одинаков.


# Оценка сложности
# Пусть n и m — длины исходных списков.
# Время обоих способов: O(n + m) в худшем случае, потому что на каждой итерации
# выбирается один узел. Цикл заканчивается, когда один список исчерпан.
# Присоединение остатка занимает O(1), обходить его по одному узлу не нужно.
# Дополнительная память: O(1) у обоих способов — несколько ссылок и, в первом
# способе, один фиктивный узел. Сам результат содержит n + m
# исходных узлов, но память для новых n + m узлов не выделяется.


# Визуализация работы алгоритма
# Узлы обозначаем буквами, чтобы различать одинаковые значения:
# a1, a2, ... — узлы первого списка; b1, b2, ... — узлы второго; D — dummy.
# В таблицах «префикс» означает только уже выбранные узлы.
# До следующего присоединения tail.next может ещё указывать на старый остаток
# исходного списка. Поэтому префикс таблицы не равен всей цепочке от head:
# невыбранные остатки отдельно доступны через list1 и list2.
#
# Пример 1: одинаковые значения, первым заканчивается list1
# list1: a1(1) -> a2(2) -> a3(4) -> None
# list2: b1(1) -> b2(3) -> b3(4) -> None
#
# Способ с фиктивным элементом
# Начало: dummy = tail = D; D.next = None; list1 = a1; list2 = b1.
#
# Шаг | Сравнение | Действие       | list1 | list2 | tail | Префикс после D
# ----|-----------|----------------|-------|-------|------|----------------
#  1  | 1 <= 1    | D.next = a1    | a2    | b1    | a1   | a1
#  2  | 2 > 1     | a1.next = b1   | a2    | b2    | b1   | a1 -> b1
#  3  | 2 <= 3    | b1.next = a2   | a3    | b2    | a2   | a1 -> b1 -> a2
#  4  | 4 > 3     | a2.next = b2   | a3    | b3    | b2   | a1 -> b1 -> a2 -> b2
#  5  | 4 <= 4    | b2.next = a3   | None  | b3    | a3   | a1 -> b1 -> a2 -> b2 -> a3
#
# На шаге 2 перезаписываем старую ссылку a1.next = a2 ссылкой на b1.
# Узел a2 не теряется: list1 всё ещё указывает на него. На шаге 3 соединяем
# b1 с a2. На каждом шаге после присоединения передвигаем tail в выбранный узел.
# После шага 5 list1 = None, цикл заканчивается. Выполняем tail.next = list2,
# то есть a3.next = b3. tail при этом остаётся a3: в коде его больше не двигаем.
# Возвращаем D.next = a1. Цепочка: a1 -> b1 -> a2 -> b2 -> a3 -> b3 -> None.
# Значения: [1, 1, 2, 3, 4, 4]. Фиктивного D в цепочке результата нет.
#
# Способ без фиктивного элемента
# Обе головы непустые. Сравниваем 1 <= 1 и выбираем head = a1.
# Передвигаем list1 на a2; устанавливаем tail = a1. list2 остаётся b1.
# Это отдельный выбор головы перед while, а не его первая итерация.
#
# Шаг | Сравнение | Действие       | list1 | list2 | tail | Префикс от head
# ----|-----------|----------------|-------|-------|------|----------------
#  1  | 2 > 1     | a1.next = b1   | a2    | b2    | b1   | a1 -> b1
#  2  | 2 <= 3    | b1.next = a2   | a3    | b2    | a2   | a1 -> b1 -> a2
#  3  | 4 > 3     | a2.next = b2   | a3    | b3    | b2   | a1 -> b1 -> a2 -> b2
#  4  | 4 <= 4    | b2.next = a3   | None  | b3    | a3   | a1 -> b1 -> a2 -> b2 -> a3
#
# Цикл завершён. Присоединяем b3 через a3.next = b3, возвращаем head = a1.
# Получаем ту же цепочку и значения [1, 1, 2, 3, 4, 4], дополнительных узлов нет.
#
# Пример 2: отрицательные числа, голова из list2, первым заканчивается list2
# list1: a1(-1) -> a2(3) -> a3(8) -> None
# list2: b1(-4) -> b2(0) -> b3(3) -> b4(5) -> None
#
# Способ с фиктивным элементом
# Начало: dummy = tail = D; D.next = None; list1 = a1; list2 = b1.
#
# Шаг | Сравнение | Действие       | list1 | list2 | tail | Префикс после D
# ----|-----------|----------------|-------|-------|------|----------------
#  1  | -1 > -4   | D.next = b1    | a1    | b2    | b1   | b1
#  2  | -1 <= 0   | b1.next = a1   | a2    | b2    | a1   | b1 -> a1
#  3  | 3 > 0     | a1.next = b2   | a2    | b3    | b2   | b1 -> a1 -> b2
#  4  | 3 <= 3    | b2.next = a2   | a3    | b3    | a2   | b1 -> a1 -> b2 -> a2
#  5  | 8 > 3     | a2.next = b3   | a3    | b4    | b3   | b1 -> a1 -> b2 -> a2 -> b3
#  6  | 8 > 5     | b3.next = b4   | a3    | None  | b4   | b1 -> a1 -> b2 -> a2 -> b3 -> b4
#
# На шаге 1 значение D = 0 не сравнивается с -4: сравниваются только головы
# входных списков. На шаге 4 равны значения a2 и b3; по условию <= выбираем a2.
# После шага 6 list2 = None, поэтому присоединяем оставшийся list1:
# b4.next = a3. Возвращаем D.next = b1; tail остаётся b4.
# Результат: b1 -> a1 -> b2 -> a2 -> b3 -> b4 -> a3 -> None.
# Значения: [-4, -1, 0, 3, 3, 5, 8].
#
# Способ без фиктивного элемента
# При выборе головы -1 <= -4 ложно. Поэтому head = b1, list2 = b2,
# tail = b1, а list1 остаётся a1. Дальше начинается while.
#
# Шаг | Сравнение | Действие       | list1 | list2 | tail | Префикс от head
# ----|-----------|----------------|-------|-------|------|----------------
#  1  | -1 <= 0   | b1.next = a1   | a2    | b2    | a1   | b1 -> a1
#  2  | 3 > 0     | a1.next = b2   | a2    | b3    | b2   | b1 -> a1 -> b2
#  3  | 3 <= 3    | b2.next = a2   | a3    | b3    | a2   | b1 -> a1 -> b2 -> a2
#  4  | 8 > 3     | a2.next = b3   | a3    | b4    | b3   | b1 -> a1 -> b2 -> a2 -> b3
#  5  | 8 > 5     | b3.next = b4   | a3    | None  | b4   | b1 -> a1 -> b2 -> a2 -> b3 -> b4
#
# Присоединяем остаток: b4.next = a3. Возвращаем head = b1.
# Получаем [-4, -1, 0, 3, 3, 5, 8]. Начальный b1 — узел второго входного списка.
