class Node:
    #узел односвязного списка

    def __init__(self, value, next_node=None):
        self.value = value
        self.next = next_node


class Stack:
#LIFO
    def __init__(self):
        self._head = None
        self._size = 0

    def push(self, value):
        #Добавить элемент на вершину стека
        self._head = Node(value, self._head)
        self._size += 1

    def pop(self):
        #Удалить и вернуть верхний элемент
        if self._head is None:
            raise IndexError("нельзя извлечь элемент из пустого стека")

        value = self._head.value
        self._head = self._head.next
        self._size -= 1
        return value

    def peek(self):
        #Вернуть верхний элемент, не удаляя его
        if self._head is None:
            raise IndexError("нельзя получить элемент из пустого стека")
        return self._head.value

    def is_empty(self):
        return self._head is None

    def __len__(self):
        return self._size


class Queue:
#FIFO
    def __init__(self):
        self._head = None
        self._tail = None
        self._size = 0

    def enqueue(self, value):
        #Добавить элемент в конец очереди
        new_node = Node(value)

        if self._tail is None:
            self._head = new_node
        else:
            self._tail.next = new_node

        self._tail = new_node
        self._size += 1

    def dequeue(self):
        #Удалить и вернуть первый элемент
        if self._head is None:
            raise IndexError("нельзя извлечь элемент из пустой очереди")

        value = self._head.value
        self._head = self._head.next
        self._size -= 1

        if self._head is None:
            self._tail = None

        return value

    def peek(self):
        #Вернуть первый элемент, не удаляя его
        if self._head is None:
            raise IndexError("нельзя получить элемент из пустой очереди")
        return self._head.value

    def is_empty(self):
        return self._head is None

    def __len__(self):
        return self._size

# Объяснение решения
# Node хранит значение и ссылку next на следующий узел односвязного списка.
# Stack и Queue реализуют стэк и очередь соответственно, самостоятельно управляют своими узлами.

# У стека _head указывает на вершину. push добавляет узел в начало,
# а pop возвращает и удаляет первый узел. Последний добавленный элемент извлекается первым.

# У очереди _head указывает на начало, а _tail — на конец. enqueue добавляет
# узел после _tail, а dequeue возвращает и удаляет _head: первым извлекается самый ранний
# из оставшихся элементов. После удаления последнего узла обнуляем и _tail,
# чтобы следующее добавление правильно создало новую очередь.
# peek возвращает значение без удаления. На пустой структуре peek и извлечение
# поднимают IndexError. _size хранит число узлов и позволяет быстро вызвать len.
# is_empty возаращает True, если структура пуста, иначе False.


# Оценка сложности
# push, pop, enqueue, dequeue, peek, is_empty и len
# работают за O(1), так как меняют или читают только несколько ссылок и полей.
# Благодаря _tail добавление в очередь не требует обхода списка.
# Память структуры — O(n), где n — число элементов; одна любая операция требует O(1)
# дополнительной памяти.


