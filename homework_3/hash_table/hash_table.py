class HashTable:
    def __init__(self, capacity=8):
        if type(capacity) is not int:
            raise TypeError("Количество корзин должно быть целым")
        if capacity <= 0:
            raise ValueError("Количество корзин должно быть >0")

        self.buckets = [[] for _ in range(capacity)]
        self.size = 0

    def __len__(self):
        return self.size

    def _find_index(self, bucket, key):
        for index, pair in enumerate(bucket):
            if pair[0] is key or pair[0] == key:
                return index
        return -1

    def put(self, key, value):
        bucket = self.buckets[hash(key) % len(self.buckets)]
        index = self._find_index(bucket, key)

        if index != -1:
            bucket[index][1] = value
            return

        bucket.append([key, value])
        self.size += 1

        # size / количество корзин >= 2/3
        if self.size * 3 >= len(self.buckets) * 2:
            self._resize()

    def get(self, key):
        bucket = self.buckets[hash(key) % len(self.buckets)]
        index = self._find_index(bucket, key)
        if index == -1:
            raise KeyError(key)
        return bucket[index][1]

    def delete(self, key):
        bucket = self.buckets[hash(key) % len(self.buckets)]
        index = self._find_index(bucket, key)
        if index == -1:
            raise KeyError(key)
        bucket.pop(index)
        self.size -= 1

    def __contains__(self, key):
        bucket = self.buckets[hash(key) % len(self.buckets)]
        return self._find_index(bucket, key) != -1

    def _resize(self):
        new_buckets = [[] for _ in range(len(self.buckets) * 2)]
        for bucket in self.buckets:
            for pair in bucket:
                index = hash(pair[0]) % len(new_buckets)
                new_buckets[index].append(pair)
        self.buckets = new_buckets


# Объяснение решения
# Хеш-таблица хранит пары «ключ — значение». Все контейнеры для хранения
# данных — списки: внешний список buckets, списки корзин и пары [key, value].
# hash() только вычисляет хеш ключа
# Начальный размер по умолчанию — 8 корзин.
#
# Номер корзины: hash(key) % len(buckets). Остаток всегда лежит в диапазоне
# от 0 до len(buckets) - 1, в том числе для отрицательного хеша.
# Разные ключи могут попасть в одну корзину(коллизия). Разрешаем её
# методом цепочек: храним все пары в списке этой корзины и перебираем их.
# Совпадения номера корзины недостаточно: _find_index сравнивает сами ключи.
# Метод возвращает индекс пары или -1, если ключа нет.
#
# put: находим корзину и ищем ключ. Если он есть, заменяем только значение.
# Если нет, добавляем новую пару и увеличиваем size — количество пар.
# После вставки нового ключа проверяем заполнение size / len(buckets).
# При достижении 2/3 или превышении этого порога удваиваем число корзин.
# Например, для 8 корзин расширение происходит на 6-й новой паре.
# Обновление существующей пары не меняет size и не вызывает расширение.
#
# _resize: создаём новый список корзин и перераспределяем все пары по формуле
# hash(key) % новый_размер. Старые индексы нельзя просто оставить, поскольку
# делитель изменился. Переносим ссылки на существующие пары, не копируя
# ключи и значения. size не меняем: число пар при переносе остаётся прежним.
# Не вызываем put при переносе: повторно искать ключи и проверять порог не нужно.
# Цепочки допускают любое число пар; расширение нужно для быстрого поиска,
# а не потому, что в списках корзин физически закончились места.
#
# get: возвращаем значение найденной пары. Если ключа нет, вызываем KeyError.
# delete: удаляем найденную пару через pop и уменьшаем size на 1.
# Отсутствующий ключ также вызывает KeyError, не меняя таблицу.
# put и delete при успехе возвращают None. len(table) возвращает size,
# а key in table проверяет наличие ключа, независимо от его значения.
# Поэтому значение None допустимо и не смешивается с отсутствием ключа.
# После удаления число корзин не уменьшаем, чтобы чередование вставок
# и удалений не вызывало постоянные перестроения таблицы.
#
# Ключи должны быть хешируемыми: строки, числа, кортежи из хешируемых
# элементов и т. п. Для списка или другого нехешируемого ключа hash()
# вызывает TypeError. Значения могут быть любыми объектами.
# Равные ключи должны иметь одинаковый хеш, а хеш и равенство ключа
# не должны меняться, пока ключ хранится в таблице. Это требования к ключам.
# Например, 1 и True равны и обозначают одну запись, как в словаре Python.
# Поля buckets и size предназначены для чтения при разборе примеров;
# изменять их вручную нельзя, иначе можно нарушить устройство таблицы.
#
# Почему все работает правильно
# Поддерживаем три свойства: каждая пара лежит в корзине hash(key) % размер;
# для каждого ключа хранится не более одной пары; size равен числу пар.
# В пустой таблице все свойства выполнены. put ищет ключ в единственной
# возможной корзине и либо обновляет его, либо добавляет одну новую пару.
# get и delete проверяют именно эту корзину, поэтому не пропускают ключ.
# Удаление одной пары не мешает находить остальные пары в цепочке.
# При расширении каждая пара переносится ровно один раз в новую правильную
# корзину, поэтому ни данные, ни количество элементов не меняются.
# Таким образом свойства сохраняются после каждой операции.


# Оценка сложности
# Пусть n — число пар, m — число корзин. Считаем вычисление хеша и сравнение
# ключей операциями O(1); для длинных строк и сложных ключей учитывается
# дополнительная стоимость этих действий.
# При равномерном распределении средняя длина цепочки — n/m. Порог 2/3
# ограничивает среднюю заполненность, поэтому get, in и delete работают
# за O(1) в среднем. pop сдвигает элементы только внутри одной цепочки.
# put без расширения также занимает O(1) в среднем, с учётом
# амортизированной стоимости append у списка Python.
# _resize требует O(m + n): создаём 2m корзин и переносим n пар.
# При расширении m = O(n), поэтому эта вставка занимает O(n).
# Благодаря удвоению размеры при последовательных расширениях образуют
# геометрическую прогрессию: суммарная стоимость переносов линейна по числу
# вставок. Поэтому put занимает O(1) в среднем амортизированно.
# Если все ключи попали в одну корзину, get, in, put и delete могут
# потребовать O(n). Расширение не устраняет одинаковые хеши разных ключей.
# len(table) работает за O(1), конструктор — за O(m).
# Память таблицы: O(m + n) — корзины и пары. Во время расширения старая
# и новая таблицы существуют одновременно, что сохраняет оценку O(m + n).
# После массовых удалений m может быть намного больше n, потому что сжатие я не делал.


# Визуализация работы алгоритма
# Начнём с HashTable(capacity=3). Для выбранных положительных целых
# hash(key) = key. Показываем только непустые корзины.
#
# Шаг | Операция       | m | n | Непустые корзины после операции
# ----|----------------|---|---|------------------------------------------
#  0  | создание       | 3 | 0 | нет
#  1  | put(1, 'A')    | 3 | 1 | 1: [[1, 'A']]
#  2  | put(4, 'B')    | 6 | 2 | 1: [[1, 'A']], 4: [[4, 'B']]
#  3  | put(7, 'C')    | 6 | 3 | 1: [[1, 'A'], [7, 'C']], 4: [[4, 'B']]
#  4  | put(7, 'X')    | 6 | 3 | 1: [[1, 'A'], [7, 'X']], 4: [[4, 'B']]
#  5  | get(7) -> 'X'  | 6 | 3 | без изменений
#  6  | delete(1)      | 6 | 2 | 1: [[7, 'X']], 4: [[4, 'B']]
#  7  | get(1)         | 6 | 2 | KeyError, таблица без изменений
#
# На шаге 2 сначала возникает коллизия: 1 % 3 = 4 % 3 = 1.
# Корзина временно содержит [[1, 'A'], [4, 'B']]. Заполнение достигает
# ровно 2/3, поэтому расширяем таблицу до 6 корзин. Теперь 1 % 6 = 1,
# а 4 % 6 = 4: перенос распределяет эти пары по разным корзинам.
# На шаге 3 возникает новая коллизия: 7 % 6 = 1 % 6 = 1.
# На шаге 4 находим ключ 7 вторым в цепочке и обновляем значение, n прежнее.
# На шаге 6 удаляем первую пару цепочки; ключ 7 остаётся доступным.


if __name__ == "__main__":
    table = HashTable(capacity=3)
    table.put(1, "A")
    table.put(4, "B")
    table.put(7, "C")
    table.put(7, "X")
    print(table.get(7))  # X
    table.delete(1)
    print(1 in table)    # False
    print(len(table))   # 2
