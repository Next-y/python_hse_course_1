from collections import Counter


def anagrams(strs):
    groups = {}

    for word in strs:
        key = frozenset(Counter(word).items())

        if key not in groups:
            groups[key] = []

        groups[key].append(word)

    return list(groups.values())


# Объяснение решения
# Анаграммы содержат одинаковые символы в одинаковых количествах.
# Counter(word) считает количество каждого символа в слове.
# Например, Counter("aab") содержит {'a': 2, 'b': 1}.
# Метод items() даёт пары «символ — количество»: ('a', 2), ('b', 1).
# frozenset превращает эти пары в неизменяемое множество: порядок пар
# не важен, а количество каждого символа сохраняется внутри пары.
# frozenset можно использовать как ключ словаря, в отличие от set
#
# В groups ключ — набор пар «символ — количество», значение — список слов.
# Для каждого слова вычисляем ключ. Если такой ключ встретился впервые,
# создаём пустую группу. Затем добавляем слово в соответствующую группу.
# groups.values() даёт представление значений словаря, то есть всех групп.
# list(groups.values()) превращает его в список списков для ответа.
#
# Почему все работает правильно
# Два ключа равны тогда и только тогда, когда у слов совпадают все символы
# и их количества. Это в точности условие того, что слова — анаграммы.
# Поэтому все анаграммы попадают в одну группу, а остальные слова — в разные.
# Каждое входное слово добавляем ровно один раз; повторы слов сохраняются.
# Обычный set(word) не подошёл бы: у "ab" и "aab" он одинаковый,
# хотя эти слова не являются анаграммами.
#
# Оценка сложности
# Пусть n — количество слов, S — суммарное количество символов во всех словах.
# Для слова длины m с d различными символами Counter занимает O(m) времени
# в среднем. Создание и хеширование frozenset, а также сравнение совпадающих
# ключей требуют O(d). При обычной работе хеш-таблиц суммарное время
# для слова — O(m + 1), так как d <= m. Единица учитывает и пустые слова.
# Итого время: O(S + n) в среднем. Это оптимально по порядку роста:
# необходимо обработать каждое слово и каждый его символ.
# Оценка предполагает O(1) для операций со счётчиками; при большом числе
# коллизий хешей операции словарей и множеств могут работать медленнее.
# Дополнительная память: O(S + n). Ключи хранят не более O(S) пар,
# группы — n ссылок на исходные строки. Сами строки не копируем.
# Временный Counter и ключ очередного слова укладываются в эту оценку.


# Визуализация работы алгоритма
# strs = ["aab", "tea", "aba", "ab", "eat", "aab"]
# Для краткости ключи обозначены буквами (порядок пар не важен):
# A = frozenset({('a', 2), ('b', 1)})
# B = frozenset({('t', 1), ('e', 1), ('a', 1)})
# C = frozenset({('a', 1), ('b', 1)})
#
# Шаг | Слово | Ключ | Группы после добавления
# ----|-------|------|-----------------------------------------------------
#  1  | aab   | A    | A: ["aab"]
#  2  | tea   | B    | A: ["aab"], B: ["tea"]
#  3  | aba   | A    | A: ["aab", "aba"], B: ["tea"]
#  4  | ab    | C    | A: ["aab", "aba"], B: ["tea"], C: ["ab"]
#  5  | eat   | B    | A: ["aab", "aba"], B: ["tea", "eat"], C: ["ab"]
#  6  | aab   | A    | A: ["aab", "aba", "aab"], B: ["tea", "eat"], C: ["ab"]
#
# На шаге 3 порядок букв другой, но ключ совпадает с A.
# На шаге 4 создаём отдельную группу: буква 'a' встречается только один раз.
# На шаге 6 сохраняем повторное слово: оно тоже присутствует во входе.
# Ответ: [["aab", "aba", "aab"], ["tea", "eat"], ["ab"]].


if __name__ == "__main__":
    strs = ["eat", "tea", "tan", "ate", "nat", "bat"]
    print(anagrams(strs))
