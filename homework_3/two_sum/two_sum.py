def two_sum(arr, k):
    seen = {}

    for i, value in enumerate(arr):
        need = k - value

        if need in seen:
            return seen[need], i

        seen[value] = i


# Объяснение решения
# По условию существует ровно одна пара разных индексов с суммой k.
# Индексы считаются с нуля. Функция возвращает их кортежем по возрастанию.
# Перебираем arr слева направо. В seen храним пары «значение: индекс»
# для уже просмотренных элементов. Для текущего value нужно найти k - value.
# Если это число есть в seen, возвращаем его индекс и текущий индекс i.
# Иначе сохраняем value с индексом i и переходим к следующему элементу.
# Исходный массив не изменяем
#
# Почему все работает правильно
# Перед каждой итерацией seen содержит все различные значения из arr[:i]
# и индекс последнего появления каждого из них в этой части массива.
# Если need найден, arr[seen[need]] + arr[i] = k.
# При этом seen[need] < i: индексы разные и уже расположены по возрастанию.
# Проверку выполняем до добавления текущего числа, поэтому один элемент
# нельзя использовать дважды. Два одинаковых числа на разных позициях
# обрабатываются правильно: для [5, 5] и k = 10 получаем (0, 1).
# Для единственной искомой пары индексов (a, b), где a < b, к моменту обработки b
# значение arr[a] уже будет в seen. Значит, алгоритм обязательно найдёт пару.
# Обновление индекса повторяющегося значения не мешает поиску дополнения.


# Оценка сложности
# Пусть n = len(arr).
# Время: O(n) в среднем. Просматриваем не более n элементов, а поиск
# и добавление в словарь занимают в среднем O(1) на операцию.
# При большом количестве коллизий хешей худшее время может быть O(n^2).
# Дополнительная память: O(n), так как seen хранит до n различных значений
# с их индексами. Остальные переменные и возвращаемая пара занимают O(1).
# Оценки предполагают, что арифметика и хеширование целых чисел стоят O(1).


# Визуализация работы алгоритма
# Пример: arr = [4, -2, 4, 0, 7, 5], k = 3.
# Единственная пара: arr[1] + arr[5] = -2 + 5 = 3.
# В таблице seen показан после выполнения шага.
#
# i | value | need = k - value | Действие           | seen
# --|-------|------------------|--------------------|---------------------------
# 0 |   4   |       -1         | Добавляем 4: 0     | {4: 0}
# 1 |  -2   |        5         | Добавляем -2: 1    | {4: 0, -2: 1}
# 2 |   4   |       -1         | Обновляем 4: 2     | {4: 2, -2: 1}
# 3 |   0   |        3         | Добавляем 0: 3     | {4: 2, -2: 1, 0: 3}
# 4 |   7   |       -4         | Добавляем 7: 4     | {4: 2, -2: 1, 0: 3, 7: 4}
# 5 |   5   |       -2         | Нашли seen[-2] = 1 | {4: 2, -2: 1, 0: 3, 7: 4}
#
# На шаге 2 повторное число 4 заменяет сохранённый индекс 0 на 2.
# На шаге 5 возвращаем (1, 5), не добавляя текущее число в словарь.
# Вывод через print(a, b): 1 5.


if __name__ == "__main__":
    arr = [1, 3, 4, 10]
    k = 7
    a, b = two_sum(arr, k)
    print(a, b)
