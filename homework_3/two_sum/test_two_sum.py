import pytest

from two_sum import two_sum


@pytest.mark.parametrize(
    "arr, k, expected",
    [
        ([1, 3, 4, 10], 7, (1, 2)),             # Пример из условия
        ([5, 5, 1, 4], 10, (0, 1)),             # Одинаковые значения
        ([2, 7], 9, (0, 1)),                   # Минимальная длина
        ([7, 2], 9, (0, 1)),                   # Порядок значений убывает
        ([0, 0], 0, (0, 1)),                   # Два нуля
        ([-5, -5], -10, (0, 1)),                # Одинаковые отрицательные
        ([-8, -3, -5, -1], -9, (0, 3)),         # Все числа отрицательные
        ([-4, 7, 1, 9], 3, (0, 1)),             # Разные знаки
        ([8, -3, 0, 3], 0, (1, 3)),             # Нулевая сумма
        ([6, 0, -2, 9], 9, (1, 3)),             # Ноль в искомой паре
        ([10, 2, 8, -3], 7, (0, 3)),            # Первый и последний элементы
        ([20, 30, 2, 5], 7, (2, 3)),            # Пара в конце
        ([3, 2, 4], 6, (1, 2)),                # Нельзя дважды взять индекс 0
        ([4, -2, 4, 0, 7, 5], 3, (1, 5)),       # Пример из визуализации
        ([10**18, 2, -10**18, 7], 0, (0, 2)),   # Большие целые числа
    ],
)
def test_two_sum(arr, k, expected):
    arr_before = arr.copy()

    result = two_sum(arr, k)

    assert result == expected
    a, b = result
    assert 0 <= a < b < len(arr)
    assert arr[a] + arr[b] == k
    assert arr == arr_before


def test_two_sum_long_array():
    # Пара находится только на последнем шаге: 0 + (-1) = -1.
    # Остальные элементы неотрицательны, поэтому других пар нет.
    arr = list(range(100_000)) + [-1]

    assert two_sum(arr, -1) == (0, 100_000)
