class Node:
    def __init__(self, value, left=None, right=None):
        self.value = value
        self.left = left
        self.right = right


def validate_bst(root):
    if root is None:
        return True

    stack = [(root, None, None)]
    while stack:
        node, lower, upper = stack.pop()
        if lower is not None and node.value <= lower:
            return False
        if upper is not None and node.value >= upper:
            return False

        if node.right is not None:
            stack.append((node.right, node.value, upper))
        if node.left is not None:
            stack.append((node.left, lower, node.value))
    return True


# Объяснение решения
# Работаем с произвольным бинарным деревом целых чисел. Node хранит value,
# left и right; None — пустое поддерево. Вход не содержит циклов и общих
# узлов. Как в задаче 1, BST строгий: дубликаты запрещены на любой глубине.
# Пустое дерево и один узел — корректные BST. Функция не изменяет дерево.
#
# Для каждого узла храним допустимый открытый интервал (lower, upper).
# None означает отсутствие границы, поэтому не ограничивает размер чисел.
# Начальный интервал не ограничен. Слева верхняя граница становится равной
# значению родителя; справа меняется нижняя. Другую границу наследуем.
# Так проверяем ограничения всех предков, а не только ближайшего родителя.
# Нарушение любой границы сразу даёт False; если стек опустел — True.
# Явный стек позволяет проверять длинные цепочки без рекурсии.
#
# Почему все работает правильно
# Интервал в стеке содержит все ограничения предков соответствующего узла.
# Корень удовлетворяет пустому набору ограничений. Переход к ребёнку
# добавляет ограничение родителя и сохраняет прежнюю противоположную границу.
# При уже проверенном родителе новая граница строже прежней с той же стороны.
# Поэтому выход за интервал означает нарушение BST, а прохождение проверки
# всеми узлами гарантирует строгий порядок во всех поддеревьях.


# Оценка сложности
# n — число узлов, h — высота в узлах. Сравнение чисел считаем O(1).
# Время: O(n) в худшем случае, каждый узел проверяется не более одного раза.
# При раннем нарушении обход прекращается; пустое дерево требует O(1).
# Дополнительная память: O(h + 1) для стека отложенных ветвей.
# Для сбалансированного дерева это O(log(n + 1)), в худшем случае O(n + 1).
# Само входное дерево в дополнительную память не включаем. Результат — O(1).
# В отличие от проверки только детей, эта оценка включает всех потомков.


# Визуализация работы алгоритма
# Пример 1: корректное дерево, результат True.
#
#          8
#        /   \
#       3     10
#      / \      \
#     1   6      14
#
# Узел | Допустимый интервал | Проверка
# -----|---------------------|---------
#  8   | без границ          | проходит
#  3   | (-inf, 8)           | проходит
#  1   | (-inf, 3)           | проходит
#  6   | (3, 8)              | проходит
# 10   | (8, +inf)           | проходит
# 14   | (10, +inf)          | проходит
# inf здесь только обозначение на схеме; в коде границами служат None.
#
# Пример 2: нарушение ограничения предка, результат False.
#
#          8
#        /   \
#       3     10
#        \
#         9
#
# 9 > 3 — условие ближайшего родителя выполнено. Но 9 находится слева
# от 8, поэтому должно быть меньше 8. Для узла 9 интервал (3, 8),
# проверка 9 >= 8 обнаруживает ошибку. До узла 10 обход уже не доходит.
#
# Пример 3: дубликат, результат False.
#       5
#      /
#     5     Интервал левого ребёнка (-inf, 5), равенство запрещено.


# Пошаговые состояния реализации
# Для примера 1 выше показываем каждую итерацию while. Запись (v, l, u)
# означает (узел со значением v, lower, upper); знак - обозначает None.
# Вершина стека справа. После проверки сначала добавляется правый ребёнок,
# затем левый: поэтому следующим извлекается левый.
#
# Шаг | pop       | Проверка границ       | stack после итерации
# ----|-----------|-----------------------|-----------------------------
#  0  | -         | начальное состояние   | [(8,-,-)]
#  1  | (8,-,-)   | нет границ            | [(10,8,-), (3,-,8)]
#  2  | (3,-,8)   | 3 < 8                 | [(10,8,-), (6,3,8), (1,-,3)]
#  3  | (1,-,3)   | 1 < 3                 | [(10,8,-), (6,3,8)]
#  4  | (6,3,8)   | 3 < 6 < 8             | [(10,8,-)]
#  5  | (10,8,-)  | 8 < 10                | [(14,10,-)]
#  6  | (14,10,-) | 10 < 14               | []
# После шага 6 условие while ложно, выполняется return True.
# Например, на шаге 2 узел 6 получает нижнюю границу 3 от родителя,
# а верхнюю 8 наследует от предка. Обе проверки видны на шаге 4.
#
# Для некорректного примера 2 последовательность заканчивается раньше:
# Шаг | pop     | Проверка              | stack / результат
# ----|---------|-----------------------|----------------------------
#  0  | -       | начальное состояние   | [(8,-,-)]
#  1  | (8,-,-) | нет границ            | [(10,8,-), (3,-,8)]
#  2  | (3,-,8) | 3 < 8                 | [(10,8,-), (9,3,8)]
#  3  | (9,3,8) | 9 > 3, но 9 >= 8      | return False
# На шаге 3 в стеке остаётся (10,8,-), но ранний return прекращает функцию.


if __name__ == "__main__":
    valid = Node(8, Node(3, Node(1), Node(6)), Node(10, right=Node(14)))
    invalid = Node(8, Node(3, right=Node(9)), Node(10))
    duplicate = Node(5, Node(5))
    print(validate_bst(valid))      # True
    print(validate_bst(invalid))    # False
    print(validate_bst(duplicate))  # False
