def max_even_sum(numbers):
    total = sum(numbers)

    if total % 2 == 0:
        return total
    
    min_odd = None

    for number in numbers:
        if number % 2 != 0:
            if min_odd is None or number < min_odd:
                min_odd = number

    if min_odd is None:
        return 0

    return total - min_odd



   # Визуализация работы алгоритма
# Сначала находим сумму всех чисел с помощью sum().
# Если сумма четная - сразу возвращаем её.
# Если сумма нечетная - проходимся по массиву и ищем минимальное нечетное число.
# Вычитаем его из общей суммы, чтобы получить максимальную четную сумму.
# Пример: [3, 8, 5] -> сумма 16, она четная, значит ответ 16.
# Пример: [3, 8, 6] -> сумма 17, она нечетная,
# минимальное нечетное число 3, значит ответ 17 - 3 = 14.

# Оценка сложности
# Временная сложность: O(n), так как мы один раз проходимся по массиву
# для подсчета суммы и в худшем случае еще один раз для поиска
# минимального нечетного числа.
# Пространственная сложность: O(1), так как используем только
# дополнительные переменные total и min_odd, количество которых
# не зависит от размера массива. 