def count_primes(n):
    count = 0

    for number in range(2, n):
        is_prime = True

        for divisor in range(2, int(number ** 0.5) + 1):
            if number % divisor == 0:
                is_prime = False
                break

        if is_prime:
            count += 1

    return count

# Визуализация работы алгоритма
# Проходимся по всем числам от 2 до N - 1.
# Для каждого числа проверяем, является ли оно простым:
# пробуем делить число на делители от 2 до квадратного корня из числа -
# этого достаточно, так как если число имеет делитель больше квадратного корня,
# то у него обязательно есть и делитель меньше квадратного корня.
# Если число делится без остатка - оно не простое.
# Если подходящего делителя нет - число простое, увеличиваем count на 1.
#
# Пример: N = 10
# Проверяем числа 2, 3, 4, 5, 6, 7, 8, 9.
# Простые числа: 2, 3, 5, 7.
# Значит, ответ: 4.

# Оценка сложности
# Временная сложность: O(n√n), так как мы проходимся по всем числам
# от 2 до N - 1, а для каждого числа в худшем случае проверяем
# делители до его квадратного корня.
# Пространственная сложность: O(1), так как используем только
# дополнительные переменные count, number, is_prime и divisor,
# количество которых не зависит от размера N.