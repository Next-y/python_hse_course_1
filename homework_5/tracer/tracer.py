from contextvars import ContextVar
from functools import wraps


_depth = ContextVar("tracer_depth", default=0)


def tracer(func):
    @wraps(func)
    def wrapper(*args, **kwargs):
        depth = _depth.get()
        print(
            f"{'  ' * depth}-> {func.__name__}("
            + ", ".join(
                [repr(arg) for arg in args]
                + [f"{key}={value!r}" for key, value in kwargs.items()]
            )
            + ")"
        )
        token = _depth.set(depth + 1)
        try:
            result = func(*args, **kwargs)
        except Exception as error:
            print(f"{'  ' * depth}!! {func.__name__}: {error!r}")
            raise
        else:
            print(f"{'  ' * depth}<- {func.__name__} = {result!r}")
            return result
        finally:
            _depth.reset(token)

    return wrapper


# Объяснение решения
# @tracer заменяет синхронную функцию обёрткой wrapper. Обёртка принимает
# любые позиционные и именованные аргументы и передаёт их исходной функции.
# -> обозначает вход: печатаем имя и аргументы через repr.
# <- обозначает выход: печатаем имя и результат, затем возвращаем сам объект.
# На каждый уровень вложенности добавляем два пробела. Глубина считается
# только для функций, к которым применён tracer; остальные вызовы не видны.
#
# ContextVar хранит общую глубину для всех обёрток в текущем контексте.
# Это позволяет показывать также вложенные вызовы разных декорированных
# функций и взаимную рекурсию. set возвращает token с прежним состоянием.
# В finally восстанавливаем его и при возврате, и при исключении, поэтому
# следующий вызов не получает лишнего отступа. Обычное исключение помечаем
# строкой !! и передаём дальше без подмены. wraps сохраняет имя, документацию
# и __wrapped__ — ссылку на исходную функцию. Генераторы и async-функции
# здесь не рассматриваем: их выполнение продолжается после вызова обёртки.
#
# Почему все работает правильно
# Перед корневым вызовом глубина равна 0. Перед каждым дочерним вызовом
# она на единицу больше глубины родителя. После завершения дочернего вызова
# finally возвращает прежнее состояние. По индукции отступ каждого входа
# соответствует числу активных декорированных предков. Локальная depth
# остаётся прежней, поэтому вход и выход одного вызова имеют равный отступ.
# Аргументы передаются без изменений; результат возвращается без копирования.
# При ошибке строки возврата нет, поскольку функция не вернула результат.
#
# Оценка сложности
# Пусть C — число вызовов, h — максимальная глубина, S — число напечатанных
# символов. При repr, линейном по длине представления, добавочное время:
# O(C + S). Для коротких аргументов отступы дают до O(C * h) символов,
# поэтому стоимость трассировки нельзя всегда считать O(C).
# При фиксированном числе аргументов дополнительная память: O(h + L),
# где O(h) — активные обёртки и токены, L — самая длинная временная строка.
# Весь журнал не храним; при перехвате stdout его хранение потребует O(S).
# Время и память самой функции прибавляются отдельно. Произвольный дорогой
# __repr__ или большая разрядность чисел могут увеличить стоимость вывода.
#
# Визуализация работы алгоритма
# Дерево вызовов fib(3), где fib(0) = 0, fib(1) = 1:
#
#             fib(3) = 2
#            /          \
#      fib(2) = 1     fib(1) = 1
#       /      \
# fib(1) = 1  fib(0) = 0
#
# Полный журнал — в том порядке, в котором выполняется реализация:
# -> fib(3)
#   -> fib(2)
#     -> fib(1)
#     <- fib = 1
#     -> fib(0)
#     <- fib = 0
#   <- fib = 1
#   -> fib(1)
#   <- fib = 1
# <- fib = 2
#
# Шаги: fib(3) ждёт fib(2); fib(2) получает 1 и 0 и возвращает 1;
# затем fib(3) вызывает правую ветвь fib(1), получает 1 и возвращает 2.
# Стек первого спуска: [fib(3)] -> [fib(3), fib(2)] ->
# [fib(3), fib(2), fib(1)]. После каждого <- последний кадр снимается.
# Повторный fib(1) справа имеет меньший отступ, потому что fib(2) уже завершён.
# Сам fib без мемоизации: O(2^n) времени сверху и O(n) памяти стека;
# декоратор добавляет вывод, но не устраняет повторные вычисления.
#
# Запуск из homework_5: python3 -m tracer.trace_calls
# Тесты всех трёх задач: python3 -m pytest -q


if __name__ == "__main__":
    @tracer
    def fib(n):
        if n < 2:
            return n
        return fib(n - 1) + fib(n - 2)

    print("Результат:", fib(3))
